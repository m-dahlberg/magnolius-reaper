#!/usr/bin/env python3
"""GUI test for Magnolius_ModulationDelay.jsfx.

@gfx runs on the UI thread and never in an offline render, and a @gfx syntax or
runtime error is invisible to every render test: the plugin loads, processes
audio correctly and simply draws nothing. This generates a debug build from the
shipped source, floats the FX window in a throwaway REAPER (-cfgfile, so your
config is untouched), and makes @gfx exercise itself:

  * @gfx runs at all, and no image slot failed to load (g_bad == 0)
  * the cents readout matches the formula
  * a simulated drag on the Time knob moves the slider through the LOG mapping
    and reaches the host (read back by ReaScript)
  * a simulated click on the Freeze toggle sets the slider and the host

It does NOT check that anything is legible: scripted capture of a JSFX pane does
not work, so how it LOOKS is for a screenshot. Needs a graphical session.

Usage: gfx_test.py        (MODDELAY_KEEP_DBG=1 keeps the generated build)
"""
import math
import os
import re
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "Magnolius_ModulationDelay.jsfx")
RES = os.path.expanduser("~/.config/REAPER")
WORK = os.environ.get("MODDELAY_WORK", os.path.expanduser("~/.cache/moddelay-rendertest"))
DBG = "Magnolius/moddelay_gfx_dbg.jsfx"

DBG_SLIDERS = """slider40:dbg_frames=0<0,1000000,1>-dbg frames
slider41:dbg_bad=-1<-1,100,1>-dbg bad
slider42:dbg_cents=0<0,1000,0.0001>-dbg cents
slider43:dbg_done=0<0,1,1>-dbg done
"""

# Appended to the END of @gfx. Fakes mouse state and calls the same widget
# functions the real panel calls, so the mapping and the host notification are
# the shipped ones.
DBG_TAIL = """
// ---- generated by tools/gfx_test.py, not part of the shipped plugin ----
gdbg_f += 1;
gdbg_f == 6 ? ( dbg_frames = gdbg_f; dbg_bad = g_bad; dbg_cents = g_cents; slider_automate(dbg_bad); slider_automate(dbg_cents); );
gdbg_f == 10 ? (
  // drag the Time knob up by 40 px: +0.2 of its (log) travel
  gk_active = 10; mouse_cap = 1; gk_lasty = mouse_y + 40*gk_S;
  g_knob(10, 0, G_XT + 8 + 36, G_R1, 1, 1, 2000, 375, 1, 0);
  gk_active = 0; mouse_cap = 0;
);
gdbg_f == 14 ? (
  // click the Freeze toggle
  gk_clicked = 1; mouse_x = (G_XL + 8 + 36 + 144)*gk_S; mouse_y = (G_R2 + 28)*gk_S;
  gk_toggle_slider(19, 9, G_XL + 8 + 36 + 144 - 14, G_R2 + 20, 28, 16, 28);
  gk_clicked = 0;
);
gdbg_f == 20 ? (
  dbg_frames = gdbg_f; dbg_done = 1;
  slider_automate(dbg_frames); slider_automate(dbg_done);
);
"""


def build_debug():
    src = open(SRC).read()
    i = src.index("\nin_pin:")
    src = src[:i] + "\n" + DBG_SLIDERS + src[i:]
    src = src.rstrip("\n") + "\n" + DBG_TAIL
    open(os.path.join(RES, "Effects", DBG), "w").write(src)


def main():
    os.makedirs(WORK, exist_ok=True)
    out = os.path.join(WORK, "gfx_result.txt")
    if os.path.exists(out):
        os.remove(out)
    res = os.path.join(WORK, "gfxres")
    shutil.rmtree(res, ignore_errors=True)
    os.makedirs(res)
    ini = [l for l in open(os.path.join(RES, "reaper.ini"))
           if not l.startswith("faultyproject=")]
    open(os.path.join(res, "reaper.ini"), "w").writelines(ini)
    for f in ("reaper-license.rk",):
        if os.path.exists(os.path.join(RES, f)):
            shutil.copy(os.path.join(RES, f), os.path.join(res, f))
    for d in ("Effects", "Data"):
        os.symlink(os.path.join(RES, d), os.path.join(res, d))

    lua = os.path.join(WORK, "gfx_probe.lua")
    open(lua, "w").write('''
local OUT = %r
reaper.InsertTrackAtIndex(0, false)
local tr = reaper.GetTrack(0, 0)
local fx = reaper.TrackFX_AddByName(tr, %r, false, -1)
reaper.TrackFX_Show(tr, fx, 3)          -- float it: @gfx only runs when shown
local names, n = {}, reaper.TrackFX_GetNumParams(tr, fx)
for i = 0, n - 1 do
  local _, nm = reaper.TrackFX_GetParamName(tr, fx, i, "")
  names[nm] = i
end
local tries = 0
local function poll()
  tries = tries + 1
  local function get(nm) return reaper.TrackFX_GetParam(tr, fx, names[nm]) end
  if (names["dbg done"] and get("dbg done") >= 1) or tries > 600 then
    local f = io.open(OUT, "w")
    f:write(string.format("frames=%%d bad=%%d cents=%%.4f time=%%.3f freeze=%%d done=%%d tries=%%d\\n",
      get("dbg frames"), get("dbg bad"), get("dbg cents"), get("Time (ms)"),
      get("Freeze"), get("dbg done"), tries))
    f:close()
    return
  end
  reaper.defer(poll)
end
poll()
''' % (out, DBG))

    build_debug()
    proc = subprocess.Popen(
        ["reaper", "-cfgfile", os.path.join(res, "reaper.ini"),
         "-newinst", "-nosplash", lua],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        deadline = time.time() + 90
        while time.time() < deadline and not os.path.exists(out):
            time.sleep(1)
        got = open(out).read().strip() if os.path.exists(out) else None
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=15)
        except subprocess.TimeoutExpired:
            proc.kill()
        if not os.environ.get("MODDELAY_KEEP_DBG"):
            try:
                os.remove(os.path.join(RES, "Effects", DBG))
            except OSError:
                pass

    if not got:
        print("gfx          FAIL  no result: @gfx never ran or never published")
        sys.exit(1)
    v = dict(kv.split("=") for kv in got.split())
    want_cents = 1200*math.log2(1 + 2*math.pi*0.6*0.0015)
    t0 = math.log(375)/math.log(2000)
    want_time = math.exp((t0 + 0.2)*math.log(2000))
    checks = [
        ("@gfx ran", int(v["done"]) == 1 and int(v["frames"]) >= 20),
        ("images loaded", int(v["bad"]) == 0),
        ("cents %.3f (want %.3f)" % (float(v["cents"]), want_cents), abs(float(v["cents"]) - want_cents) < 0.01),
        ("time knob drag -> %.1f ms (want %.1f)" % (float(v["time"]), want_time),
         abs(float(v["time"]) - want_time)/want_time < 0.01),
        ("freeze toggle -> %d" % int(v["freeze"]), int(v["freeze"]) == 1),
    ]
    ok = all(c for _, c in checks)
    print("gfx          %s  %s" % ("PASS" if ok else "FAIL",
                                  "; ".join("%s%s" % (n, "" if c else " [FAIL]") for n, c in checks)))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
