#!/usr/bin/env python3
"""GUI smoke test for Magnolius_Saturator.jsfx.

@gfx runs on the UI thread and NEVER runs in an offline render, so
render_test.py cannot reach the panel at all -- a @gfx section with a syntax
error still lets every render_test pass, including "params".

This drives the panel for real.  It generates a debug build from the shipped
source, floats the FX window in a throwaway REAPER instance (@gfx only runs
when the window is shown) and has @gfx publish results through hidden
sliders, which a ReaScript reads back.

What it pins:
  * @gfx compiles and actually runs (a frame counter advances), including
    after every slider is driven to its extremes;
  * a control change made on the UI thread reaches the AUDIO PATH.  Neither
    slider_automate() nor sliderchange() re-runs @slider, and @block never
    runs on a stopped track, so the panel calls recalc() itself.  Reading the
    slider back would pass even with a dead DSP; this reads back audio-side
    DERIVED values (gin_tg, sym_tg, kn_tg, aw_tg, mix_tg, lat_tg) instead.

What it does NOT pin: whether anything is legible or correctly laid out.  Ask
for a screenshot for that.

Runs in an isolated resource directory (-cfgfile), so your REAPER config is
untouched.  Needs a graphical session.

Usage: gfx_test.py            (SAT_KEEP_DBG=1 keeps the generated build)
"""
import os
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "Magnolius_Saturator.jsfx")
RES = os.path.expanduser("~/.config/REAPER")
WORK = os.environ.get("SAT_WORK", os.path.expanduser("~/.cache/saturator-rendertest"))
# Written next to the real plugin's gui_kit/ so the image paths resolve.
DBG_DIR = os.path.join(RES, "Effects", "Magnolius")
DBG = "_SaturatorGfxDbg.jsfx"

DBG_SLIDERS = """slider20:dbg_alive=-1<-1,99999,1>-dbg alive
slider21:dbg_gin=-999<-999,999,0.001>-dbg gin
slider22:dbg_sym=-999<-999,999,0.001>-dbg sym
slider23:dbg_knee=-999<-999,999,1>-dbg knee
slider24:dbg_auto=-999<-999,999,1>-dbg auto
slider25:dbg_mix=-999<-999,999,0.001>-dbg mix
slider26:dbg_lat=-999<-999,999,1>-dbg lat
slider27:dbg_done=-1<-1,9999,1>-dbg done
"""

# Appended to the END of @gfx.  Does what a knob drag does: write the slider,
# slider_automate it by bitmask, then let the frame's own recalc() path run.
DBG_TAIL = """
// ---- generated by tools/gfx_test.py, not part of the shipped plugin ----
gdbg_f += 1;
gdbg_f == 10 ? (
  input_db = 6;  slider_automate(2^0);
  slew = 40;     slider_automate(2^1);
  asym = 30;     slider_automate(2^2);
  sym = 40;      slider_automate(2^3);
  knee = 2;      slider_automate(2^4);
  output_db = -3; slider_automate(2^5);
  auto_gain = 0; slider_automate(2^6);
  mix = 50;      slider_automate(2^7);
  os_i = 2;      slider_automate(2^8);
  recalc();
);
gdbg_f == 25 ? (
  // extremes, then keep drawing: NaN/inf in the scaling would show up as a
  // dead panel
  input_db = 18; slew = 100; asym = 100; sym = 100; knee = 0; output_db = 18;
  auto_gain = 1; mix = 0; os_i = 0; recalc();
  input_db = -18; slew = 0; asym = 0; sym = 0; knee = 1; output_db = -18;
  auto_gain = 0; mix = 100; os_i = 1; recalc();
  input_db = 6; slew = 40; asym = 30; sym = 40; knee = 2; output_db = -3;
  auto_gain = 0; mix = 50; os_i = 2; recalc();
);
gdbg_f == 45 ? (
  dbg_alive = gdbg_f; dbg_gin = gin_tg; dbg_sym = sym_tg; dbg_knee = kn_tg;
  dbg_auto = aw_tg; dbg_mix = mix_tg; dbg_lat = lat_tg; dbg_done = 1;
  slider_automate(2^19); slider_automate(2^20); slider_automate(2^21);
  slider_automate(2^22); slider_automate(2^23); slider_automate(2^24);
  slider_automate(2^25); slider_automate(2^26);
);
"""


def build_debug():
    src = open(SRC).read()
    i = src.index("\nin_pin:")
    src = src[:i] + "\n" + DBG_SLIDERS + src[i:]
    src = src.rstrip("\n") + "\n" + DBG_TAIL
    open(os.path.join(DBG_DIR, DBG), "w").write(src)

def main():
    os.makedirs(WORK, exist_ok=True)
    out = os.path.join(WORK, "gfx_result.txt")
    if os.path.exists(out):
        os.remove(out)

    # isolated resource dir: reaper.ini is never touched, and a stale
    # "faultyproject" flag there cannot pop a modal and hang the run
    res = os.path.join(WORK, "gfxres")
    shutil.rmtree(res, ignore_errors=True)
    os.makedirs(res)
    ini = [l for l in open(os.path.join(RES, "reaper.ini"))
           if not l.startswith("faultyproject=")]
    open(os.path.join(res, "reaper.ini"), "w").writelines(ini)
    for f in ("reaper-license.rk",):
        if os.path.exists(os.path.join(RES, f)):
            shutil.copy(os.path.join(RES, f), os.path.join(res, f))
    for d in ("Effects", "Data"):
        os.symlink(os.path.join(RES, d), os.path.join(res, d))

    lua = os.path.join(WORK, "gfx_probe.lua")
    open(lua, "w").write('''
local OUT = %r
reaper.InsertTrackAtIndex(0, false)
local tr = reaper.GetTrack(0, 0)
local fx = reaper.TrackFX_AddByName(tr, %r, false, -1)
if fx < 0 then
  local f = io.open(OUT, "w"); f:write("ADD_FAILED\\n"); f:close(); return
end
reaper.TrackFX_Show(tr, fx, 3)          -- float it: @gfx only runs when shown
local names, n = {}, reaper.TrackFX_GetNumParams(tr, fx)
for i = 0, n - 1 do
  local _, nm = reaper.TrackFX_GetParamName(tr, fx, i, "")
  names[nm] = i
end
local tries = 0
local function get(nm)
  if names[nm] == nil then return -12345 end
  return reaper.TrackFX_GetParam(tr, fx, names[nm])
end
local function poll()
  tries = tries + 1
  if get("dbg done") >= 0 or tries > 400 then
    local f = io.open(OUT, "w")
    f:write(string.format("alive=%%d gin=%%.4f sym=%%.4f knee=%%d auto=%%d mix=%%.4f lat=%%d done=%%d tries=%%d\\n",
      get("dbg alive"), get("dbg gin"), get("dbg sym"), get("dbg knee"), get("dbg auto"),
      get("dbg mix"), get("dbg lat"), get("dbg done"), tries))
    f:close()
    return
  end
  reaper.defer(poll)
end
poll()
''' % (out, DBG))

    build_debug()
    proc = subprocess.Popen(
        ["reaper", "-cfgfile", os.path.join(res, "reaper.ini"), lua],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        t0 = time.time()
        while time.time() - t0 < 60 and not os.path.exists(out):
            time.sleep(0.25)
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
        if not os.environ.get("SAT_KEEP_DBG"):
            os.remove(os.path.join(DBG_DIR, DBG))

    if not os.path.exists(out):
        print("gfx            FAIL  no result -- REAPER never ran the panel")
        return 1
    txt = open(out).read().strip()
    if "ADD_FAILED" in txt:
        print("gfx            FAIL  debug build would not load: " + txt)
        return 1
    kv = dict(p.split("=") for p in txt.split())
    checks = [
        ("@gfx compiles and runs", float(kv["alive"]) >= 45),
        ("Input 6 dB reaches the audio path (gin_tg == 6)", abs(float(kv["gin"]) - 6) < 0.001),
        ("Symmetric 40 % reaches the audio path (sym_tg == 0.4)", abs(float(kv["sym"]) - 0.4) < 0.001),
        ("Knee Hard reaches the audio path (kn_tg == 2)", abs(float(kv["knee"]) - 2) < 0.01),
        ("Auto Gain off reaches the audio path (aw_tg == 0)", abs(float(kv["auto"])) < 0.01),
        ("Mix follows (mix_tg == 0.5)", abs(float(kv["mix"]) - 0.5) < 0.001),
        ("Oversampling 4x sets the latency (lat_tg == 46)", abs(float(kv["lat"]) - 46) < 0.01),
    ]
    bad = [n for n, ok in checks if not ok]
    print("gfx            %s  %s" % ("PASS" if not bad else "FAIL", txt))
    for n, ok in checks:
        print("    %s %s" % ("ok  " if ok else "FAIL", n))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
