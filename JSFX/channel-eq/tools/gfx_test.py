"""GUI smoke test for Magnolius_ChannelEQ.jsfx.

@gfx runs on the UI thread and NEVER runs in an offline render, so
render_test.py cannot reach the panel at all -- a @gfx section with a syntax
error still lets every render_test pass, including "params".

This drives the panel for real.  It generates a debug build from the shipped
source, floats the FX window in a throwaway REAPER instance (@gfx only runs
when the window is shown) and has @gfx publish results through hidden
sliders, which a ReaScript reads back.

What it pins:
  * @gfx compiles and actually runs (a frame counter advances), including after
    every slider is driven to its extremes;
  * every image the panel loads resolved (the failed-load counter is 0);
  * the panel's own copy of the laws and prototypes (the response curve) gives
    the full-boost bell gain at its centre, +21 dB, so the curve is drawn from
    the real sliders;
  * hiding the curve switches the panel to the shorter layout.

What it does NOT pin: whether anything is legible or correctly laid out, and
that the audio path follows a knob (an offline render cannot move a knob, and
@block does not run on a stopped track).  Ask for a screenshot for the layout.

Runs in an isolated resource directory (-cfgfile), so your REAPER config is
untouched.  Needs a graphical session.

Usage: gfx_test.py            (CHEQ_KEEP_DBG=1 keeps the generated build)
"""
import os
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "Magnolius_ChannelEQ.jsfx")
RES = os.path.expanduser("~/.config/REAPER")
WORK = os.environ.get("CHEQ_WORK", os.path.expanduser("~/.cache/chnl-eq-rendertest"))
# Written next to the real plugin's gui_kit/ so the image paths resolve.
DBG_DIR = os.path.join(RES, "Effects", "Magnolius")
DBG = "_ChannelEQGfxDbg.jsfx"

DBG_SLIDERS = """slider30:dbg_alive=-1<-1,99999,1>-dbg alive
slider31:dbg_curve=-999<-999,999,0.001>-dbg curve
slider32:dbg_h=-999<-999,9999,1>-dbg h
slider33:dbg_bad=-1<-1,99,1>-dbg bad
slider34:dbg_done=-1<-1,9999,1>-dbg done
"""

# Appended to the END of @gfx.  Does what a knob drag does: write the slider,
# slider_automate it by bitmask, then let the frame's own drawing run.
DBG_TAIL = """
// ---- generated by tools/gfx_test.py, not part of the shipped plugin ----
gdbg_f += 1;
gdbg_f == 10 ? (
  hmf_g = 1; slider_automate(2^10);
  hmf_f = 0.5; slider_automate(2^11);
  hmf_q = 0; slider_automate(2^12);
  hmf_x3 = 0; slider_automate(2^13);
);
gdbg_f == 25 ? (
  // extremes, then keep drawing: NaN/inf in the maths would show up as a dead panel
  hpf = 1; lpf = 0; lf_g = -1; lf_f = 0; lmf_g = 1; lmf_f = 1; lmf_q = 1; lmf_d3 = 1;
  hmf_g = -1; hmf_f = 1; hmf_q = 1; hmf_x3 = 1; hf_g = 1; hf_f = 1; gain_law = 1;
);
gdbg_f == 35 ? (
  hpf = 0; lpf = 1; lf_g = 0; lmf_g = 0; hf_g = 0; hmf_g = 1; hmf_f = 0.5; hmf_q = 0; hmf_x3 = 0; gain_law = 0;
);
gdbg_f == 50 ? (
  g_protos();
  gdbg_f0 = sqrt(G_PROTO[4*8 + 5])/(2*$pi);
  dbg_curve = 8.685889638065037*log(g_mag(4, gdbg_f0));
  curve_on = 0;
);
gdbg_f == 60 ? (
  dbg_alive = gdbg_f; dbg_h = g_uih; dbg_bad = g_bad; dbg_done = 1;
  slider_automate(2^29); slider_automate(2^30); slider_automate(2^31);
  slider_automate(2^32); slider_automate(2^33);
);
"""


def build_debug():
    src = open(SRC).read()
    i = src.index("\nin_pin:")
    src = src[:i] + "\n" + DBG_SLIDERS + src[i:]
    src = src.rstrip("\n") + "\n" + DBG_TAIL
    open(os.path.join(DBG_DIR, DBG), "w").write(src)

def main():
    os.makedirs(WORK, exist_ok=True)
    out = os.path.join(WORK, "gfx_result.txt")
    if os.path.exists(out):
        os.remove(out)

    # isolated resource dir: reaper.ini is never touched, and a stale
    # "faultyproject" flag there cannot pop a modal and hang the run
    res = os.path.join(WORK, "gfxres")
    shutil.rmtree(res, ignore_errors=True)
    os.makedirs(res)
    ini = [l for l in open(os.path.join(RES, "reaper.ini"))
           if not l.startswith("faultyproject=")]
    open(os.path.join(res, "reaper.ini"), "w").writelines(ini)
    for f in ("reaper-license.rk",):
        if os.path.exists(os.path.join(RES, f)):
            shutil.copy(os.path.join(RES, f), os.path.join(res, f))
    for d in ("Effects", "Data"):
        os.symlink(os.path.join(RES, d), os.path.join(res, d))

    lua = os.path.join(WORK, "gfx_probe.lua")
    open(lua, "w").write('''
local OUT = %r
reaper.InsertTrackAtIndex(0, false)
local tr = reaper.GetTrack(0, 0)
local fx = reaper.TrackFX_AddByName(tr, %r, false, -1)
if fx < 0 then
  local f = io.open(OUT, "w"); f:write("ADD_FAILED\\n"); f:close(); return
end
reaper.TrackFX_Show(tr, fx, 3)          -- float it: @gfx only runs when shown
local names, n = {}, reaper.TrackFX_GetNumParams(tr, fx)
for i = 0, n - 1 do
  local _, nm = reaper.TrackFX_GetParamName(tr, fx, i, "")
  names[nm] = i
end
local tries = 0
local function get(nm)
  if names[nm] == nil then return -12345 end
  return reaper.TrackFX_GetParam(tr, fx, names[nm])
end
local function poll()
  tries = tries + 1
  if get("dbg done") >= 0 or tries > 400 then
    local f = io.open(OUT, "w")
    f:write(string.format("alive=%%d curve=%%.3f h=%%d bad=%%d done=%%d tries=%%d\\n",
      get("dbg alive"), get("dbg curve"), get("dbg h"), get("dbg bad"),
      get("dbg done"), tries))
    f:close()
    return
  end
  reaper.defer(poll)
end
poll()
''' % (out, DBG))

    build_debug()
    proc = subprocess.Popen(
        ["reaper", "-cfgfile", os.path.join(res, "reaper.ini"), lua],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        t0 = time.time()
        while time.time() - t0 < 60 and not os.path.exists(out):
            time.sleep(0.25)
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
        if not os.environ.get("CHEQ_KEEP_DBG"):
            os.remove(os.path.join(DBG_DIR, DBG))

    if not os.path.exists(out):
        print("gfx            FAIL  no result -- REAPER never ran the panel")
        return 1
    txt = open(out).read().strip()
    if "ADD_FAILED" in txt:
        print("gfx            FAIL  debug build would not load: " + txt)
        return 1
    kv = dict(p.split("=") for p in txt.split())
    checks = [
        ("@gfx compiles and runs", float(kv["alive"]) >= 60),
        ("every image resolved (failed-load counter == 0)", float(kv["bad"]) == 0),
        ("curve drawn from the real sliders: full boost at the HMF centre == +21 dB",
         abs(float(kv["curve"]) - 21.0) < 0.05),
        ("hiding the curve selects the short layout (348)", float(kv["h"]) == 348),
    ]
    bad = [n for n, ok in checks if not ok]
    print("gfx            %s  %s" % ("PASS" if not bad else "FAIL", txt))
    for n, ok in checks:
        print("    %s %s" % ("ok  " if ok else "FAIL", n))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
